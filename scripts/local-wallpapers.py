"""Build the local-only wallpaper set from ./wallpapers (git-ignored) into app/assets (also git-ignored).

./wallpapers/catalog.json lists {file, id, name}. Photos are centre-cropped to fill 1920x1080 (no stretch).
Needs Pillow (dev only), Node and the repo's Playwright install for the glass materials.
Run: python3 scripts/local-wallpapers.py
"""
import json, shutil, subprocess
from pathlib import Path
from PIL import Image, ImageOps, ImageStat

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'wallpapers'
WALL = ROOT / 'app/assets/wallpapers'
MAT = ROOT / 'app/assets/materials'
LOCAL = 'local-'
entries = json.loads((SRC / 'catalog.json').read_text())

for d in (WALL, MAT):   # clear previous local output only; the bundled default stays
    for f in d.glob('local-*'):
        f.unlink()

def lum(img, box):
    return ImageStat.Stat(img.crop(box).convert('L')).mean[0] / 255

catalog = []
for e in entries:
    with Image.open(SRC / e['file']) as original:
        original.load()
        profile = original.info.get('icc_profile')
        image = ImageOps.exif_transpose(original).convert('RGB')
    bg = ImageOps.fit(image, (1920, 1080), Image.Resampling.LANCZOS, centering=(0.5, 0.5))   # cover: fills, never stretches
    extra = {'icc_profile': profile} if profile else {}
    bg.save(WALL / (LOCAL + e['id'] + '.jpg'), quality=90, subsampling=0, **extra)
    bg.resize((512, 288), Image.Resampling.LANCZOS).save(WALL / (LOCAL + e['id'] + '-thumb.jpg'), quality=85, subsampling=2, **extra)
    tone = 'light' if lum(bg, (0, 0, 1920, 432)) > .42 else 'dark'
    catalog.append({
        'id': LOCAL + e['id'], 'name': e['name'], 'src': 'assets/wallpapers/%s.jpg' % (LOCAL + e['id']), 'thumb': 'assets/wallpapers/%s-thumb.jpg' % (LOCAL + e['id']),
        'tone': tone,
        'ut': {'tr': 'mist' if lum(bg, (1216, 72, 1800, 140)) > .5 else 'light', 'br': 'mist' if lum(bg, (1216, 940, 1800, 1010)) > .5 else 'light'},
        'frostVeil': .2 if tone == 'light' else .12, 'listColumn': 0, 'dockQuiet': False,
        'clockMist': lum(bg, (140, 72, 500, 140)) > .5})
(WALL / 'local-catalog.js').write_text('/* Local wallpapers replacing the bundled default (generated by scripts/local-wallpapers.py; not committed). */\nwindow.CleanFrameWallpapers = ' + json.dumps(catalog, indent=2) + ';\n')

sources = WALL / 'SOURCES.json'
keep = sources.read_text()
sources.write_text(json.dumps([{'id': c['id']} for c in catalog]))   # temporary: build-materials reads this
subprocess.run(['node', 'scripts/build-materials.mjs', ','.join(c['id'] for c in catalog)], cwd=ROOT, check=True)
sources.write_text(keep)
out = ROOT / '.local/materials/builder'
for c in catalog:
    shutil.copy(out / (c['id'] + '-panel.jpg'), WALL)
    for s in ('field-blur', 'field-frost', 'field-clear', 'study-soft'):
        shutil.copy(out / ('%s-%s.jpg' % (c['id'], s)), MAT)
print('ok', [c['id'] + ':' + c['tone'] for c in catalog])
